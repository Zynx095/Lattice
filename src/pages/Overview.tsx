import { useMemo } from 'react'
import { useNavigate } from 'react-router-dom'
import { Inbox, Plus, Sparkles } from 'lucide-react'
import { aiPrompts, appConfig, cap, dashboardMetrics, isEnabled, modules, quickActions } from '@/config'
import { statusMeta, type RecordStatus, type WorkRecord } from '@/data/models'
import { aiSource, useAsync } from '@/lib/ai'
import { dayKey } from '@/lib/utils'
import { countPerDay, lastDays } from '@/lib/metrics'
import { aiService } from '@/services/ai/ai.service'
import { activityStore, recordsStore } from '@/store'
import { AIError } from '@/components/ai/AIParts'
import { BarList, ChartPanel, LineChart } from '@/components/charts/Charts'
import { ActivityFeed, MetricStrip, QuickActions } from '@/components/dashboard/Dashboard'
import { PageHeader } from '@/components/shell/PageHeader'
import { Button, EmptyState, Panel, Skeleton } from '@/components/ui'

const DAYS = 14
const statusColor: Record<string, string> = {
  [statusMeta.open.label]: 'bg-info',
  [statusMeta.in_progress.label]: 'bg-warning',
  [statusMeta.blocked.label]: 'bg-danger',
  [statusMeta.done.label]: 'bg-success',
}

interface Brief {
  overall: string
  trends?: string[]
  outstanding?: string[]
  issues?: string[]
  actions?: string[]
}

/**
 * Compact, structured summary of the records for the AI. Owner names are left out:
 * the analysis doesn't need them, so they are not sent to an external provider.
 */
function briefContext(records: WorkRecord[]): string {
  const today = dayKey(Date.now())
  const open = records.filter((r) => r.status !== 'done')
  const overdue = open.filter((r) => r.dueDate < today)
  const added = countPerDay(records, DAYS, (r) => r.createdAt)
  const completed = countPerDay(records, DAYS, (r) => r.completedAt)
  const half = (xs: number[]) => [xs.slice(0, DAYS / 2).reduce((a, b) => a + b, 0), xs.slice(DAYS / 2).reduce((a, b) => a + b, 0)]
  const [addedPrev, addedLast] = half(added)
  const [donePrev, doneLast] = half(completed)
  const byStatus = (Object.keys(statusMeta) as RecordStatus[]).map((s) => `${statusMeta[s].label} ${records.filter((r) => r.status === s).length}`).join(', ')
  const byCategory = [...new Set(open.map((r) => r.category))].map((c) => `${c} ${open.filter((r) => r.category === c).length}`).join(', ')
  return [
    `Today: ${today}. Total ${appConfig.entity.plural}: ${records.length}.`,
    `By status: ${byStatus}.`,
    `Open by category: ${byCategory || 'none'}.`,
    `Overdue (open, past due date): ${overdue.length}. High priority open: ${open.filter((r) => r.priority === 'high').length}.`,
    `Added: previous 7 days ${addedPrev}, last 7 days ${addedLast}. Completed: previous 7 days ${donePrev}, last 7 days ${doneLast}.`,
    `Open items (title | category | status | priority | due):`,
    ...open
      .sort((x, y) => x.dueDate.localeCompare(y.dueDate))
      .slice(0, 30)
      .map((r) => `- ${r.title} | ${r.category} | ${statusMeta[r.status].label} | ${r.priority} | due ${r.dueDate}${r.dueDate < today ? ' (overdue)' : ''}`),
  ].join('\n')
}

function BriefList({ title, items }: { title: string; items?: string[] }) {
  if (!items?.length) return null
  return (
    <div>
      <h3 className="text-sm font-medium">{title}</h3>
      <ul className="mt-1 list-disc space-y-1 pl-5 text-muted-foreground">
        {items.map((it, i) => <li key={i}>{it}</li>)}
      </ul>
    </div>
  )
}

/** A short AI-written read of the current data, generated by the backend router on request. */
function AssistantBrief() {
  const records = recordsStore.use()
  const brief = useAsync<{ data: Brief; source: string }>()

  const generate = () =>
    brief.run(async () => {
      const res = await aiService.generateJSON<Brief>(
        [
          { role: 'user', content: briefContext(records) },
          { role: 'user', content: aiPrompts.brief },
        ],
        { systemPrompt: aiPrompts.system },
      )
      if (!res.data || typeof res.data.overall !== 'string') throw new Error('The AI answered in an unexpected format. Try again.')
      return { data: res.data, source: aiSource(res) }
    })

  return (
    <Panel
      title="Assistant brief"
      description="An AI analysis of the current data, written on request."
      actions={
        <Button variant="secondary" size="sm" leftIcon={<Sparkles />} isLoading={brief.status === 'loading'} onClick={generate}>
          {brief.status === 'done' ? 'Regenerate' : 'Generate brief'}
        </Button>
      }
    >
      {brief.status === 'idle' && (
        <p className="text-muted-foreground">
          Claude or Gemini reads a summary of all {records.length} {appConfig.entity.plural} (owner names are not sent) and reports status, trends, outstanding items, risks and next actions.
        </p>
      )}
      {brief.status === 'loading' && (
        <div className="space-y-2" aria-busy="true">
          <Skeleton className="h-4 w-11/12" />
          <Skeleton className="h-4 w-full" />
          <Skeleton className="h-4 w-2/3" />
        </div>
      )}
      {brief.status === 'error' && <AIError message={brief.error!} onRetry={generate} />}
      {brief.status === 'done' && brief.data && (
        <div className="space-y-4">
          <p className="max-w-prose leading-relaxed">{brief.data.data.overall}</p>
          <div className="grid gap-4 sm:grid-cols-2">
            <BriefList title="Trends" items={brief.data.data.trends} />
            <BriefList title="Outstanding" items={brief.data.data.outstanding} />
            <BriefList title="Potential issues" items={brief.data.data.issues} />
            <BriefList title="Next actions" items={brief.data.data.actions} />
          </div>
          <p className="text-xs text-subtle">Generated by {brief.data.source}</p>
        </div>
      )}
    </Panel>
  )
}

export default function Overview() {
  const records = recordsStore.use()
  const activity = activityStore.use()
  const navigate = useNavigate()

  const metrics = useMemo(() => dashboardMetrics.map((m) => ({ id: m.id, label: m.label, ...m.compute(records) })), [records])
  const chart = useMemo(() => {
    const labels = lastDays(DAYS).map((d) => d.label)
    const added = countPerDay(records, DAYS, (r) => r.createdAt)
    const completed = countPerDay(records, DAYS, (r) => r.completedAt)
    return { labels, added, completed }
  }, [records])
  const byStatus = useMemo(
    () => (Object.keys(statusMeta) as RecordStatus[]).map((s) => ({ label: statusMeta[s].label, value: records.filter((r) => r.status === s).length })),
    [records],
  )

  const actions = quickActions.filter((a) => isEnabled(a.module))
  const noun = appConfig.entity

  return (
    <>
      <PageHeader
        title={modules.overview.title}
        description={modules.overview.description}
        actions={
          isEnabled('records') && (
            <Button leftIcon={<Plus />} onClick={() => navigate(`${modules.records.path}?new=1`)}>New {noun.singular}</Button>
          )
        }
      />

      <MetricStrip metrics={metrics} />

      <div className="mt-5 grid gap-5 lg:grid-cols-3">
        <div className="space-y-5 lg:col-span-2">
          {records.length === 0 ? (
            <Panel>
              <EmptyState
                icon={Inbox}
                title={`No ${noun.plural} yet`}
                description={`Add your first ${noun.singular} and this page fills in with totals, trends and activity.`}
                action={isEnabled('records') && <Button onClick={() => navigate(`${modules.records.path}?new=1`)}>Add a {noun.singular}</Button>}
              />
            </Panel>
          ) : (
            <ChartPanel
              title="Added and completed"
              description={`${cap(noun.plural)} per day, last ${DAYS} days`}
              table={{
                columns: ['Day', 'Added', 'Completed'],
                rows: chart.labels.map((l, i) => [l, chart.added[i], chart.completed[i]]),
              }}
            >
              <LineChart
                labels={chart.labels}
                series={[
                  { label: 'Added', values: chart.added },
                  { label: 'Completed', values: chart.completed },
                ]}
              />
            </ChartPanel>
          )}
          {isEnabled('assistant') && <AssistantBrief />}
        </div>

        <div className="space-y-5">
          {actions.length > 0 && (
            <Panel title="Quick actions">
              <QuickActions actions={actions} />
            </Panel>
          )}
          <Panel title="By status" description={`All ${records.length} ${noun.plural}`}>
            <BarList data={byStatus} colorFor={(label) => statusColor[label]} />
          </Panel>
          <Panel title="Recent activity">
            <ActivityFeed entries={activity} />
          </Panel>
        </div>
      </div>
    </>
  )
}
